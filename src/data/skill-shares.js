// nodeNames = ArkPassive.Effects[].Description에서 '깨달음 1티어 ' 같은 접두사를 뗀 노드 이름 배열(crit.js의 nodeName 규칙).
// 공식 API 값은 '잔재된 기운 Lv.3'처럼 레벨이 붙어 오므로 뒤의 ' Lv.N'을 떼고 비교한다.
// 첫 일치 빌드를 돌려주고, 직업·빌드 자료가 없으면 null.
const bareNode = (name) => String(name).replace(/\s*Lv\.?\s*\d+\s*$/, '').trim();
export function findBuild(className, nodeNames) {
  const builds = SKILL_SHARES[className];
  if (!Array.isArray(builds) || !Array.isArray(nodeNames)) return null;
  const names = new Set(nodeNames.map(bareNode));
  return builds.find((b) => names.has(b.detect.node)) ?? null;
}
