// 택1 상자 판정: 첫 아이템이 이 목록과 정확히 일치하면 아이템 중 비싼 쪽만 반영
// (접두사 매칭 금지 — '운명의 돌파석'이 '운명의 돌'로 오인되는 것 방지)
const CHOICE_LEADERS = ['운명의 돌', '운명의 파괴석', '운명의 파괴석 결정'];

function optionName(items) {
  const first = items[0][0];
  const hit = OPTION_NAMES.find(([name]) => first === name);
  return hit ? hit[1] : first;
}

// /효율 커맨드가 쓰는 형태로 변환. 없는 조합이면 null.
export function buildTable(content, tier, stage) {
  const stages = REWARDS[content]?.[tier];
  const s = stages?.[stage];
  if (!s) return null;

  const options = s.options.map((items) => ({
    name: optionName(items),
    parts: CHOICE_LEADERS.includes(items[0][0]) ? [{ choice: items }] : items,
  }));

  return {
    label: `[시즌3] ${content} ${tier} - ${stage}단계`,
    base: s.base,
    options,
  };
}
